#!/bin/sh
# Re-fetch the public ECB reference rates used for FX simulation (USD base).
curl -sL "https://api.frankfurter.app/2024-11-01..2026-11-06?from=USD&to=MXN,BRL,EUR" -o /tmp/fx.json
python3 - <<'PY'
import json
d=json.load(open('/tmp/fx.json')); r=d['rates']; ks=sorted(r)
out={"source":"European Central Bank reference rates via api.frankfurter.app (USD base)","from":ks[0],"to":ks[-1],"dates":ks,"MXN":[r[k]['MXN'] for k in ks],"BRL":[r[k]['BRL'] for k in ks],"EUR":[r[k]['EUR'] for k in ks]}
open('data/fx_usd.json','w').write(json.dumps(out))
open('src/fxdata.js','w').write('// Generated by scripts/fetch_fx.sh from public ECB reference rates (api.frankfurter.app).\nexport const FX = '+json.dumps(out)+';\n')
PY
